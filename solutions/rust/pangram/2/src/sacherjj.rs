pub fn char_bit(ch: char) -> u32 {
    match ch {
        'a' => 0b1,
        'b' => 0b10,
        'c' => 0b100,
        'd' => 0b1000,
        'e' => 0b10000,
        'f' => 0b100000,
        'g' => 0b1000000,
        'h' => 0b10000000,
        'i' => 0b100000000,
        'j' => 0b1000000000,
        'k' => 0b10000000000,
        'l' => 0b100000000000,
        'm' => 0b1000000000000,
        'n' => 0b10000000000000,
        'o' => 0b100000000000000,
        'p' => 0b1000000000000000,
        'q' => 0b10000000000000000,
        'r' => 0b100000000000000000,
        's' => 0b1000000000000000000,
        't' => 0b10000000000000000000,
        'u' => 0b100000000000000000000,
        'v' => 0b1000000000000000000000,
        'w' => 0b10000000000000000000000,
        'x' => 0b100000000000000000000000,
        'y' => 0b1000000000000000000000000,
        'z' => 0b10000000000000000000000000,
        _ => 0,
    }
}

// Verbose but fast.
pub fn is_pangram(sentence: &str) -> bool {
    let mut bit_map: u32 = 0;
    for ch in sentence.to_lowercase().chars() {
        bit_map |= char_bit(ch);

        if bit_map == 0b11111111111111111111111111 {
            return true;
        }
    }
    false
}
